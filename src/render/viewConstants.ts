/**
 * ボールの高さ(z) を画面上の持ち上げ量へ変換する係数。
 *
 * ★段階1で 1.6 → 3.2★ 実測すると最大弾道 (zVel上限6.0 → 頂点51.2px) でも画面上
 * わずか5〜8%しか上がらず、ロングフィード/センタリング/ハイシュートが「浮いている」
 * ように見えなかった (docs/screen-geometry.md D-3)。原作の弾道の手応えに寄せるため強調する。
 * 上げすぎるとボールが地平線やスタンドへ飛び込むので、最大弾道でも地平線より十分下に
 * 留まることを確認して決めた値。
 * ★24周目-6 (台帳L-01のズームに伴う再スケーリング) で 3.2 → 4.5★
 * 持ち上げ量は heightPx×p.scale×係数 で画面スケールに従属するため、ズームで最遠の
 * ボールの上昇量が 8% を割った (6.0%)。係数を上げて 通常19.8%/最遠8.4% に回復
 * (cameraBehavior.test.ts ゲート4)。原作の浮き球は画面上端近くまで舞い上がる
 * (台帳 vf1876-1904) ため、方向としても原作へ寄る。
 */
export const BALL_HEIGHT_LIFT_SCALE = 4.5;

/**
 * 高いボールほど大きく描く (カメラに近づくため)。1px あたりの拡大率。
 * ★24周目-6 (台帳L-02) で 0.012 → 0.03★ 原作 (vf690/vf1888) は最高弾道でボールが
 * 地上の約2.5〜3倍まで拡大する。最大高さ≈52px × 0.03 = +1.56 → 2.56倍で原作帯に一致。
 * 旧値0.012は最大でも1.6倍で「浮いている感」が出なかった。
 */
export const BALL_HEIGHT_GROW_PER_PX = 0.03;

/**
 * 高いボールほど接地影をわずかに縮める。1px あたりの縮小率。
 * ★24周目-6 (台帳L-02) で 0.035 → 0.004★ 旧値は最大高さで影が1/2.8に縮み、さらに
 * 同係数で透明化もしていたため、浮き球ほど影が消えていた (原作と正反対)。
 * 原作の影は浮遊中も濃く残る (高さの手がかりは影とボールの分離距離 + ボールの拡大)。
 * 縮小は「気持ち程度」(最大高さで約17%減) に留め、透明化は行わない (PitchScene側)。
 */
export const BALL_SHADOW_SHRINK_PER_PX = 0.004;

