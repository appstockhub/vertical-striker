/**
 * ★段階1 (ピッチスケールとカメラの確定) の調整パラメータを1箇所に集めたもの★
 *
 * 背景: 画面の見え方を決める値が projection.ts / PitchScene.ts / playerSprites.ts に
 * 散らばっており、「原作に寄せる」ための試行錯誤がしづらかった。原作比較で動かす可能性が
 * ある値だけをここへ集約し、`npm run view:metrics` (tests/render/viewMetrics.test.ts) が
 * 同じ値を読んで対比表を出す、という一本の経路にする。
 *
 * ★ここは描画専用★ — sim/ からは決して import しないこと (決定論に影響させない)。
 * ピッチの論理寸法 (config/pitch.ts の PITCH_WIDTH/PITCH_HEIGHT) は sim/ の距離しきい値が
 * 全て相対的に依存しているため、見た目の調整は原則としてこちら側 (投影) で行う。
 */

// ============================================================================
// 投影 (カメラの位置と画角)
// ============================================================================

/**
 * 地平線の画面Y比。この上はスタンド/空で、プレーには使えない領域になる。
 * 小さくするほど空が狭く、ピッチが画面を広く占める。
 */
export const HORIZON_Y_FRAC = 0.18;

/**
 * 画面下端に写る地面の、カメラからの奥行き (ワールドpx)。
 * これが「一番手前に見えるもの」の距離であり、実質的なズーム倍率を決める
 * (小さいほど寄る = 手前が大きく写り、見える範囲が狭くなる)。
 *
 * ★24周目-6 (台帳L-01: カメラが引きすぎ) で 300 → 112.5★
 * 横長化(1280x720)の際、俯角(16.7°)だけを保存して可視範囲の不変条件を見落とした結果、
 * ボール位置の可視ワールド幅が選手35.7人分(原作9人分)まで広がっていた。
 * 俯角は focal のみで決まる (tan俯角 = (0.68H - horizonY)/focal) ため、
 * focal = R×viewportWidth×nearDepth/PITCH_WIDTH = 1200 を保つ制約
 * **R × nearDepth = 450** の下で nearDepth を選ぶのがズームの正しい自由度。
 * nearDepth=112.5 (R=4.0) で可視幅は選手13.4人分になる — 原作4:3の9人分を
 * 16:9の幅比(1.5倍)で換算した値 (9×1.5=13.5人分) にほぼ一致する。
 * 画面下端に写る地面はカメラから約16m — 原作実測の可視範囲 15〜64m の近端とも一致。
 */
export const NEAR_DEPTH = 112.5;

/**
 * 上記 nearDepth の位置で、ピッチ幅が画面幅の何倍に見えるか。
 * 実質的には**カメラの高さ**を決めるパラメータ (camHeight = (H - horizonY) / R)。
 * 大きいほどカメラが低く構え、俯角が浅くなり、ピッチが画面に対して大きく写る。
 *
 * ★段階1後の訂正で 1.18 → 4.0★
 * 段階1では「ピッチが選手に対して3.6倍細い。直すにはPITCH_WIDTHを変える(=AI全面再調整)」と
 * 結論したが誤りだった。「ピッチが選手の何人分の幅か」は選手の**描画上の**大きさとの比であり、
 * それを決めているのは sim ではなくこの R。実測 (npm run view:metrics):
 *
 *   R=1.18(旧): カメラ俯角 45.4° / ピッチ幅 = 選手 9.6人分
 *   R=4.0(新):  カメラ俯角 16.7° / ピッチ幅 = 選手 32.7人分
 *   原作(実測): カメラ俯角 15〜22° / ピッチ幅 = 選手 約34.5人分
 *
 * 旧値の俯角45°は原作(15〜22°)よりはるかに急で、「地面を見下ろしている」画になっていた。
 * これが「原作に全く見えない」最大の原因。sim は一切変更していない。
 *
 * ★24周目: 画面横長化 (config/pitch.ts VIEWPORT_WIDTH 480→1280) に伴う再導出★
 * この定数は camHeight = (viewportHeight-horizonY)*PITCH_WIDTH/(R*viewportWidth) を介して
 * 俯角を決める。viewportWidth を変えても俯角(=camHeightで決まる)を維持するには、
 * R を viewportWidth の変化に反比例させる必要がある (R*viewportWidth = 一定を保つ)。
 * 480→1280 は2.667倍なので、R も 4.0/2.667 ≈ 1.5 にする。これにより:
 *   - camHeight・俯角・「ピッチ幅=選手32.7人分」は完全に不変 (視野角の縦方向は無関係)
 *   - near depth で見えるワールド幅は PITCH_WIDTH/R に比例して増える (120→320px)。
 *     横長画面いっぱいに、伸縮させずに「より広く」ピッチを見せる、が意図どおりの効果
 * 実測 (npm run view:metrics) で俯角16.7°・ピッチ幅32.7人分・地平線Y比18.1%が
 * 変更前と一致することを確認済み。
 *
 * ★24周目-6 (台帳L-01) で 1.5 → 4.0★ NEAR_DEPTH のコメント参照。
 * 俯角の不変条件 R × NEAR_DEPTH = 450 を保ったまま、ズームを原作の框へ寄せた
 * (R=1.5/nearDepth=300 → R=4.0/nearDepth=112.5。focal=1200 は不変)。
 */
export const NEAR_WIDTH_RATIO = 4.0;

