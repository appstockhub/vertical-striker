/**
 * ★段階1 (ピッチスケールとカメラの確定) の調整パラメータを1箇所に集めたもの★
 *
 * 背景: 画面の見え方を決める値が projection.ts / PitchScene.ts / playerSprites.ts に
 * 散らばっており、「原作に寄せる」ための試行錯誤がしづらかった。原作比較で動かす可能性が
 * ある値だけをここへ集約し、`npm run view:metrics` (tests/render/viewMetrics.test.ts) が
 * 同じ値を読んで対比表を出す、という一本の経路にする。
 *
 * ★ここは描画専用★ — sim/ からは決して import しないこと (決定論に影響させない)。
 * ピッチの論理寸法 (config/pitch.ts の PITCH_WIDTH/PITCH_HEIGHT) は sim/ の距離しきい値が
 * 全て相対的に依存しているため、見た目の調整は原則としてこちら側 (投影) で行う。
 */

// ============================================================================
// 投影 (カメラの位置と画角)
// ============================================================================

/**
 * 地平線の画面Y比。この上はスタンド/空で、プレーには使えない領域になる。
 * 小さくするほど空が狭く、ピッチが画面を広く占める。
 */
export const HORIZON_Y_FRAC = 0.18;

/**
 * 画面下端に写る地面の、カメラからの奥行き (ワールドpx)。
 * これが「一番手前に見えるもの」の距離であり、実質的なズーム倍率を決める
 * (小さいほど寄る = 手前が大きく写り、見える範囲が狭くなる)。
 */
export const NEAR_DEPTH = 300;

/**
 * 上記 nearDepth の位置で、ピッチ幅が画面幅の何倍に見えるか。
 * 1.0 で near のタッチラインがちょうど画面端。1 より大きいほど手前の左右が画面外へ出て、
 * 「低い位置から見ている」強い遠近感になる。
 */
export const NEAR_WIDTH_RATIO = 1.18;

// ============================================================================
// カメラ追従
// ============================================================================

/**
 * 注視点 (ボール) を画面のどこに置くか (画面高さに対する比)。
 * 大きいほどボールが画面下寄り = 前方 (攻撃方向) の情報量が増える。
 * 18周目に 0.66 → 0.76 (画面下半分が空く構図が頻発したため)。
 */
export const FOCUS_SCREEN_Y_FRAC = 0.76;

/** カメラ追従のイージング係数 (0..1、1に近いほど速く貼り付く)。 */
export const CAMERA_SMOOTHING = 0.12;

/** 進行方向の先読みオフセットの上限 (ワールドpx)。縦視点の「奥が見えない」弱点を補う。 */
export const LOOK_AHEAD_MAX = 90;

/** 先読みが上限に達するボール速度 (px/tick)。 */
export const LOOK_AHEAD_VEL_REF = 3;

// ============================================================================
// 選手の見かけサイズ
// ============================================================================

/**
 * 選手の見かけサイズの補正。厳密な投影スケールのままだと選手が小さすぎて背番号も
 * 向きも読めないため、「視認性 > 幾何的な正確さ」で持ち上げる (描画専用の演出係数)。
 */
export const PLAYER_SIZE_BOOST = 1.4;

/**
 * 選手スプライトの「実際に人が描かれている高さ」(キャンバス高さ46pxのうち、
 * 頭頂 y=3 から接地 y=45 までの42px)。キャンバス高さではなくこちらが見かけの身長になる。
 * playerSprites.ts の drawPlayerSprite() の骨格寸法から導出した値。
 */
export const PLAYER_SPRITE_FIGURE_HEIGHT = 42;

// ============================================================================
// レーダー
// ============================================================================

/**
 * レーダーの不透明度。1.0 未満にすると裏のプレー領域が透けて、右サイドが完全な死角に
 * ならない。大きさ自体は config/pitch.ts の RADAR_WIDTH。
 */
export const RADAR_ALPHA = 0.82;
