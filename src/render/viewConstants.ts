/**
 * 注視点 (ボール) を画面のどこに置くか (画面高さに対する比)。
 * 大きいほどボールが画面下寄り = 前方 (攻撃方向) の情報量が増える。
 *
 * 経緯: 18周目に 0.66 → 0.76 (画面下半分が空く構図が頻発したため)。
 * ★段階1で 0.76 → 0.68★ 空きの真因はピッチ外が暗い虚無だったことで、芝のランオフ
 * (pitchPerspective.ts) を入れて解消したため、原作の実測値 (プレーの中心が画面Y 55〜60%) 側へ
 * 戻す。あわせて LOOK_AHEAD_MAX を下げ、先読みが効いた状態でもボールが画面Y 80% を
 * 超えない (= 下端に貼り付いて進行方向が見えなくならない) ようにした。
 * この不変条件は tests/render/cameraBehavior.test.ts が回帰ゲートとして守る。
 */
export const FOCUS_SCREEN_Y_FRAC = 0.68;

/** カメラ追従のイージング係数 (0..1、1に近いほど速く貼り付く)。 */
export const CAMERA_SMOOTHING = 0.12;

/**
 * 進行方向の先読みオフセットの上限 (ワールドpx)。縦視点の「奥が見えない」弱点を補う。
 * ★段階1で 90 → 75★ 先読みが最大に効くとボールが画面下へ押し下げられるため
 * (注視点より手前に取り残されるので画面Yが増える)、上限を下げて 80% 以内に収める。
 * ★24周目-6 (台帳L-01) で 75 → 28★ ズームで「ボール〜画面下端」のワールド距離が
 * 192px → 72px に縮んだため、先読みも同比率で縮めないとボールが画面下端へ
 * 押し出される (75×72/192 ≈ 28)。画面上の先読み"見え方"の比率は不変。
 */
export const LOOK_AHEAD_MAX = 28;

/** 先読みが上限に達するボール速度 (px/tick)。
 * テンポ変更(24周目サイクル①): 3×BALL_TEMPO(0.3)=0.9。強キック(2.7)で確実に飽和し、
 * ドリブル速度(0.63)では部分的、という旧比率を保存する。 */
export const LOOK_AHEAD_VEL_REF = 0.9;

/**
 * ★24周目・カメラ揺れ対策★ 先読み用ボール速度の平滑化係数 (camera.ts smoothBallVelocity)。
 * 位置追従の CAMERA_SMOOTHING (0.12) より意図的に遅くする — こちらは「ドリブルタッチの
 * 単発スパイク(周期9〜10tick)を潰す」ことが目的で、位置追従とは別の周波数特性が要る。
 *
 * 導出: 1次IIRフィルタの周期10tickでのゲイン |H(ω)| (ω=2π/10) を計算すると、
 *   α=0.12(現行の位置追従と同値): 20.3% (すり抜けが大きい、現に揺れとして知覚される)
 *   α=0.04(採用値):                 6.6%  (タッチスパイクをほぼ潰す)
 * 一方でステップ応答の立ち上がりは 1/α ≈ 25tick (0.42秒) — 強いキック直後に先読みが
 * 最大まで乗るのに約0.4秒かかる計算だが、キックの速度自体が摩擦0.968/tickで
 * 減衰するのは数十〜100tick超かけてなので体感的な遅れにはならない。ドリブルは
 * 常時発生する(プレイ時間の大半)のに対し、強シュートは疎な事象であるため、
 * 「頻発する揺れの根絶」を「稀な先読み立ち上がりの一瞬の遅れ」より優先する。
 */
export const LOOK_AHEAD_VEL_SMOOTHING = 0.04;

/**
 * ★横追従★ カメラのワールドXがボールを追う際の、ピッチ幅に対するクランプ範囲。
 *
 * 経緯: NEAR_WIDTH_RATIO を原作の俯角に合わせた結果、ボール位置で画面に写るワールド幅が
 * 667px → 約197px に狭まり、**480px幅のピッチ全体が画面に入らなくなった**。
 * そのままだとタッチライン際のボールが画面外に出てしまうため、横方向の追従が必須になった
 * (Phase 0 の「横スクロールは行わない」という前提は、俯角45°で全幅が入っていたから
 * 成立していたにすぎない)。
 *
 * 0.15〜0.85 にクランプすると、ボールが x=0 の隅にいても camX=72 で
 * ボールとの差は72px、可視半幅は約98pxなので画面内に収まる。
 */
export const CAMERA_X_MIN_FRAC = 0.15;
export const CAMERA_X_MAX_FRAC = 0.85;
/** 横追従のイージング係数。縦(0.12)よりゆっくりにして、左右の揺れを抑える。 */
export const CAMERA_X_SMOOTHING = 0.08;

