/**
 * 選手の見かけサイズの較正係数。
 *
 * ★24周目-6 (台帳L-01) で 1.4 → 3.73 (幾何学的に正確な値へ再導出)★
 * スプライトのキャンバス上の人物高さは 42px (PLAYER_SPRITE_FIGURE_HEIGHT)、
 * 選手のワールド身長は 14.68px。near位置(p.scale=1)で幾何学的に正しい画面上の身長は
 *   14.68 × nearScale = 14.68 × (focal/NEAR_DEPTH) = 14.68 × 10.667 ≈ 156.6px
 * なので、boost = 156.6 / 42 ≈ 3.73 が「投影とスプライトの縮尺が一致する」値。
 * 旧値1.4は「視認性のため幾何を無視して持ち上げる」演出係数だったが、L-01のズームで
 * スプライトは十分大きくなったため、以後は幾何学的に正確な縮尺で描く
 * (実測: ボール位置の選手身長 ≈ 画面幅の7.5% — 原作実測の 手前11%/奥7% の帯に入る)。
 */
export const PLAYER_SIZE_BOOST = 3.73;

/**
 * 選手スプライトの「実際に人が描かれている高さ」(キャンバス高さ46pxのうち、
 * 頭頂 y=3 から接地 y=45 までの42px)。キャンバス高さではなくこちらが見かけの身長になる。
 * playerSprites.ts の drawPlayerSprite() の骨格寸法から導出した値。
 */
export const PLAYER_SPRITE_FIGURE_HEIGHT = 42;

