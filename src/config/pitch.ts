// ピッチ/ビューポート寸法の純定数。Phaser には依存しない。
// 単位はすべて「論理ピクセル」(整数)。sim/ 側では toFixed() して使う。

/**
 * ビューポート（画面に見える範囲）の論理解像度。
 *
 * ★24周目・実プレイ報告「画面が縦長で原作と全く違う」を受けて変更 (480x720縦長 → 1280x720横長)★
 * Phase 0 は CLAUDE.md の「縦長ピッチ（比率 縦:横 ≈ 1.5:1）」を「ビューポート側の比率」と
 * 解釈し、画面自体を縦長(480x720、2:3)にしていた。しかしこの解釈は docs/screen-geometry.md
 * 6節で「文言はピッチであり、実寸比1:1.54とも一致するため、この仮定自体が誤りだった
 * 可能性が高い」と既に指摘されており、原作の実測 (scratchpad/reference動画のクロップ
 * 1668x883 ≒ 1.89:1、SNESネイティブ256x224も横伸び込みで同水準) は一貫して横長だった。
 * 「縦長ピッチ」は実世界のピッチ形状(105m×68m=1:1.54、縦スクロールで辿る対象)を指し、
 * それを映す画面(SFC実機のテレビ)自体は横長 — 当実装は対象と器を混同していた。
 * 1280x720 (16:9=1.78、原作実測1.89に近い標準解像度) へ変更する。
 */
export const VIEWPORT_WIDTH = 1280;
export const VIEWPORT_HEIGHT = 720;

/**
 * ピッチ全体（スクロールする試合フィールド）の論理サイズ。
 *
 * ★上記のビューポート変更に伴い、PITCH_WIDTH を独立定数へ切り離した★
 * 旧実装は `PITCH_WIDTH = VIEWPORT_WIDTH` (画面幅と1:1) だったが、横方向にもカメラが
 * 追従する現行実装 (render/camera.ts followCameraWorldX、段階1後の訂正で導入) では
 * この等式に意味が無く、画面幅を変えるたびにピッチの論理寸法(=sim/の全距離しきい値の基準)が
 * 連動して動いてしまう副作用がある。480 (旧VIEWPORT_WIDTH と同値) に固定し、sim/ 側の
 * 挙動・全テストのしきい値を無変更に保つ (画面比率の変更は描画層 render/viewConstants.ts の
 * NEAR_WIDTH_RATIO 側で吸収する。詳細は同ファイルのコメント参照)。
 * 高さは旧実装の値 (720 × 2.5 = 1800) をそのまま維持する (sim/ の全距離しきい値・
 * 統計ゲート・決定論のいずれにも影響させない、という上記の方針どおり。数値だけ独立させ、
 * 導出式の基準をVIEWPORT_HEIGHTからPITCH_WIDTHへ変えるとPITCH_HEIGHTの実値が動いてしまう
 * ため、あえて即値のまま固定する)。
 */
export const PITCH_WIDTH = 480;
export const PITCH_HEIGHT = 1800;

/**
 * レーダー(ミニマップ)の画面上のサイズと余白。
 *
 * ★段階1で 0.22 → 0.15★ ピッチが 1:3.75 と極端に縦長なため、レーダーも同じ比率で
 * 縦に長くなり、幅22%でも画面高さの55%を占めて右側のプレー領域を丸ごと隠していた
 * (自己観察キャプチャ `.shots/before-*.png`)。CLAUDE.md の「レーダーの視認性・情報量には
 * 妥協しない」方針は維持しつつ、プレーの視界を奪わない大きさに収める。
 */
export const RADAR_WIDTH = Math.round(VIEWPORT_WIDTH * 0.15);
export const RADAR_HEIGHT = Math.round(RADAR_WIDTH * (PITCH_HEIGHT / PITCH_WIDTH));
export const RADAR_MARGIN = 10;
