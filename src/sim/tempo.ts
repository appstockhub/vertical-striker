/**
 * ★テンポ係数 (24周目、サイクル①)★ — docs/parity-targets.md T1〜T4 ゲートの実装。
 *
 * 原作動画の実測 (選手身長=1 に正規化、n=198/148/11):
 *   - 走速     med 2.15 身長/s → 0.526 px/tick   (現行 3.0 の 5.7倍遅い)  … T1
 *   - キック初速 med 11.0 身長/s → 2.70 px/tick   (現行 9.0 の 3.3倍遅い)  … T2
 *   - キック/走速比 5.2 (現行 3.0)                                        … T3
 *   - 転がり摩擦 0.965/tick (現行 0.985)                                   … T4
 *
 * 実装方針: 既存の調律値 (数百時間ぶんのバグ修正の履歴を持つ相対関係) を捨てずに、
 * 「係数を掛ける」形でスケールする。
 *   - 速度を α 倍、加速度を α² 倍、時間窓を 1/α 倍にすると、空間的な軌道は完全に保存され、
 *     時間だけが 1/α 倍に引き伸ばされる (= 相対バランス無傷のテンポ変更)。
 *   - ただし T3 (比の修正) のため、選手系 (RUN_TEMPO) とボール系 (BALL_TEMPO) は
 *     別の係数にする。これは意図的な相対バランスの変更 (原作準拠へ)。
 *
 * どちらの係数を使うかの基準:
 *   - 選手の移動・選手に追従するボール (ドリブル系)・選手が体で押すボール (タックル系)
 *     → RUN_TEMPO
 *   - 蹴られたボール (キック/パス/シュート)・その判定しきい値 (GKキャッチ上限等)
 *     → BALL_TEMPO
 *   - ボールの加速度 (重力・カーブ) → BALL_TEMPO²
 *   - 選手の行動時間 (タックルの溜め/判定/隙) → 1/RUN_TEMPO (移動距離を保存)
 *   - 人間の反応時間・同時押し猶予に由来する窓 → スケールしない (実時間の人間都合)
 */

/** 選手系の速度係数。3.0 px/tick → 0.525 px/tick = 2.15 身長/s (T1ゲート中央値)。 */
export const RUN_TEMPO = 0.175;

/** ボール系(キック)の速度係数。9.0 px/tick → 2.70 px/tick = 11.0 身長/s (T2ゲート)。 */
export const BALL_TEMPO = 0.3;

/** ボール系の加速度係数 (重力・カーブ)。軌道の空間形状を保存する。 */
export const BALL_TEMPO_SQ = BALL_TEMPO * BALL_TEMPO;

/** 選手の行動時間 (tick窓) の引き伸ばし。移動距離 = 速度×時間 を保存する。 */
export function runTicks(ticks: number): number {
  return Math.round(ticks / RUN_TEMPO);
}

/** ボール由来の時間窓 (カーブ持続等) の引き伸ばし。 */
export function ballTicks(ticks: number): number {
  return Math.round(ticks / BALL_TEMPO);
}
